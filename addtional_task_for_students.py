def my_count(l: list, item):
    count = 0  # переменная для хранения количества вхождений
    for element in l:  # проходим по каждому элементу списка
        if element == item:  # проверяем равенство текущего элемента и искомого
            count += 1       # увеличиваем счётчик, если нашли совпадение
    return count           # возвращаем итоговое число вхождений

# пример использования:
lst = [1, 2, 3, 2, 4, 2]
print(my_count(lst, 2))  
